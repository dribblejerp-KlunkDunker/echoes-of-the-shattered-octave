#!/usr/bin/env python3
"""Scan img/painted/**.jpg and write js/painted-manifest.js and img/painted/README.md.

Run from anywhere: python3 tools/art/manifest.py
Re-run after adding or replacing paintings. The manifest only says which files exist;
js/painted.js decides at run time whether each one loads.
"""
import json
import os
import struct
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
PAINTED = os.path.join(ROOT, 'img', 'painted')


def jpeg_size(path):
    """Width and height from the JPEG start-of-frame marker (no imaging library needed)."""
    with open(path, 'rb') as f:
        d = f.read()
    i = 2
    while i + 9 < len(d):
        if d[i] != 0xFF:
            i += 1
            continue
        m = d[i + 1]
        if m in (0xD8, 0x01) or 0xD0 <= m <= 0xD7:
            i += 2
            continue
        (n,) = struct.unpack('>H', d[i + 2:i + 4])
        if 0xC0 <= m <= 0xCF and m not in (0xC4, 0xC8, 0xCC):
            h, w = struct.unpack('>HH', d[i + 5:i + 9])
            return w, h
        i += 2 + n
    return 0, 0


def main():
    entries = {}
    for group in sorted(os.listdir(PAINTED)) if os.path.isdir(PAINTED) else []:
        gdir = os.path.join(PAINTED, group)
        if not os.path.isdir(gdir):
            continue
        for name in sorted(os.listdir(gdir)):
            stem, ext = os.path.splitext(name)
            if ext.lower() != '.jpg' or not stem.replace('_', '').isalnum():
                continue
            p = os.path.join(gdir, name)
            w, h = jpeg_size(p)
            entries[group + '/' + stem] = {'w': w, 'h': h, 'bytes': os.path.getsize(p)}
    body = ',\n'.join('  %s: %s' % (json.dumps(k), json.dumps(v, separators=(', ', ': ')).replace('"w"', 'w').replace('"h"', 'h').replace('"bytes"', 'bytes'))
                      for k, v in entries.items())
    js = "// Generated by tools/art/manifest.py from img/painted/. Do not edit by hand.\n'use strict';\n"
    js += 'const PAINTED_MANIFEST = {' + ('\n' + body + '\n' if entries else '') + '};\n'
    with open(os.path.join(ROOT, 'js', 'painted-manifest.js'), 'w') as f:
        f.write(js)
    os.makedirs(PAINTED, exist_ok=True)
    lines = ['# Painted art', '', 'Generated by tools/art/manifest.py. Paintings for area cards, death and ending screens and logbook sketches;',
             'js/painted.js uses each one when present and falls back to the procedural stand-in otherwise.', '']
    if not entries:
        lines.append('No paintings yet.')
    for k, v in entries.items():
        lines.append('- `%s.jpg` - %dx%d, %d bytes' % (k, v['w'], v['h'], v['bytes']))
    with open(os.path.join(PAINTED, 'README.md'), 'w') as f:
        f.write('\n'.join(lines) + '\n')
    print('%d paintings' % len(entries))


if __name__ == '__main__':
    sys.exit(main())
