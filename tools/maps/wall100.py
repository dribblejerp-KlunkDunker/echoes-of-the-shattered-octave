#!/usr/bin/env python3
"""Phase 100: Null-Watch's ground plan, cut from the Rift city's own cymatic figure.

Reads the Cymatic City Engine's plan of the 852 Hz city (cy_rift.json: fundamentalHz 48, seed 1, preset City, the same
file the Phase 89 and 90 sheets were drawn from) and lays the heart's window of it into the game's cells: from the west
gate across the Talking Halls at the centre to the wall on the east rim and Tower Nine in the north-east. 372 x 133
cells, a cell a step and a half (the city is 500 steps across, Phase 90). Streets and rings become the garrison's
streets, the bold nodal lines its broad ways, the buildings its barrack blocks, and everything else is built up solid.
Nothing is random.

  python3 tools/maps/wall100.py /path/to/cy_rift.json          writes js/rift100_grid.js and screenshots/p100/plan.png
"""
import json, os, sys, math
from PIL import Image, ImageDraw

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = sys.argv[1] if len(sys.argv) > 1 else '/tmp/cy_rift.json'
X0, X1 = -1.03, 1.20            # the window, in city radii (east is the Rift)
Y0, Y1 = -0.66, 0.14
RC = 500 / 1.5 / 2              # the city's radius in cells
W, H = int(round((X1 - X0) * RC)), int(round((Y1 - Y0) * RC))
SS = 4
SOLID, STREET, RING, BROAD, HOUSE, OUT = 0, 1, 2, 3, 4, 5
CH = '.,=#Ho'                   # built up solid, street, ring street, broad way, barrack block, outside the rim

def main():
    d = json.load(open(SRC))
    R = max(max(abs(r[0]), abs(r[1]), abs(r[2]), abs(r[3])) for r in d['roads'])
    sx = W * SS / ((X1 - X0) * R); sy = H * SS / ((Y1 - Y0) * R)
    P = lambda x, y: ((x / R - X0) * R * sx, (y / R - Y0) * R * sy)
    cell_m = (X1 - X0) * R / W
    layers = {k: Image.new('L', (W * SS, H * SS), 0) for k in (STREET, RING, BROAD, HOUSE)}
    dr = {k: ImageDraw.Draw(v) for k, v in layers.items()}
    for b in d['b']:
        x, y, bw, bd, rot = b[0], b[1], b[2], b[3], (b[6] if len(b) > 6 else 0)
        c, s = math.cos(rot), math.sin(rot)
        dr[HOUSE].polygon([P(x + c * dx - s * dy, y + s * dx + c * dy) for dx, dy in ((-bw / 2, -bd / 2), (bw / 2, -bd / 2), (bw / 2, bd / 2), (-bw / 2, bd / 2))], fill=255)
    for r in d['roads']:
        k = BROAD if r[5] == 'boulevard' else RING if r[5] in ('ring', 'wall') else STREET
        w = max(1, int(round(r[4] / cell_m * SS * (1.0 if k == BROAD else 0.8))))
        dr[k].line([P(r[0], r[1]), P(r[2], r[3])], fill=255, width=w)
    small = {k: v.resize((W, H), Image.BOX) for k, v in layers.items()}
    grid = []
    for j in range(H):
        row = ''
        for i in range(W):
            nx = X0 + (i + 0.5) / W * (X1 - X0); ny = Y0 + (j + 0.5) / H * (Y1 - Y0)
            v = lambda k: small[k].getpixel((i, j))
            if math.hypot(nx, ny) > 1.0: t = OUT
            elif v(BROAD) > 70: t = BROAD
            elif v(RING) > 90 or v(STREET) > 90: t = RING if v(RING) >= v(STREET) else STREET
            elif v(HOUSE) > 110: t = HOUSE
            else: t = SOLID
            row += CH[t]
        grid.append(row)
    def rle(s):
        out, i = [], 0
        while i < len(s):
            j = i
            while j < len(s) and s[j] == s[i]: j += 1
            n = j - i; out.append((str(n) if n > 1 else '') + s[i]); i = j
        return ''.join(out)
    js = ['// Generated by tools/maps/wall100.py from the Cymatic City Engine\'s 852 Hz plan of Null-Watch (do not edit).',
          '// ' + str(W) + ' x ' + str(H) + ' cells, a cell a step and a half; rows run-length coded: ' + repr(CH) + ' = built up, street, ring street, broad way, barrack block, outside the rim.',
          "'use strict';",
          'const RIFT100_GRID = { w: %d, h: %d, x0: %s, x1: %s, y0: %s, y1: %s, rc: %s, key: %s, rows: [' % (W, H, X0, X1, Y0, Y1, round(RC, 4), json.dumps(CH))]
    js += ['  %s,' % json.dumps(rle(r)) for r in grid]
    js += ['] };', "if (typeof window !== 'undefined') window.RIFT100_GRID = RIFT100_GRID;", "if (typeof module !== 'undefined' && module.exports) module.exports = RIFT100_GRID;", '']
    open(os.path.join(ROOT, 'js', 'rift100_grid.js'), 'w').write('\n'.join(js))
    col = {'.': (40, 38, 44), ',': (150, 146, 140), '=': (176, 170, 160), '#': (210, 150, 80), 'H': (74, 70, 80), 'o': (96, 100, 104)}
    im = Image.new('RGB', (W, H))
    for j, r in enumerate(grid):
        for i, ch in enumerate(r): im.putpixel((i, j), col[ch])
    os.makedirs(os.path.join(ROOT, 'screenshots', 'p100'), exist_ok=True)
    im.resize((W * 4, H * 4), Image.NEAREST).save(os.path.join(ROOT, 'screenshots', 'p100', 'plan.png'))
    print(W, H, 'cell', round(cell_m, 1), 'm;', {k: sum(r.count(k) for r in grid) for k in CH})

main()
