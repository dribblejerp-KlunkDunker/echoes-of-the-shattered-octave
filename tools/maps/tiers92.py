#!/usr/bin/env python3
"""Phase 92: the Umbral Tiers' ground plan, cut from Sol-Luminary's own cymatic figure.

Reads the Cymatic City Engine's plan of the 528 Hz city (cy_heights.json: fundamentalHz 48, seed 1, preset City,
the same file the Phase 89 and 90 sheets were drawn from) and lays the heart's window of it, from just above the
line down to the Keel Docks, into the game's cells: 160 x 226 cells, a cell a step and a half (the city is 500
steps across, Phase 90). Streets and rings become walkways, the boulevards (the figure's bold nodal lines) the
chain-walks, the buildings the hanging houses, and everything else the gulf. Nothing is random.

  python3 tools/maps/tiers92.py /tmp/cy_heights.json          writes js/heights92_grid.js and screenshots/p92/plan.png
"""
import json, os, sys, math
from PIL import Image, ImageDraw

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = sys.argv[1] if len(sys.argv) > 1 else '/tmp/cy_heights.json'
W, H = 160, 226
X0, X1 = -0.48, 0.48          # the window, in city radii (y down: the docks at the bottom, the line at the top)
Y0, Y1 = -0.40, 0.95
SS = 4                          # supersampling for the lines
GULF, STREET, RING, CHAIN, HOUSE, ROCK = 0, 1, 2, 3, 4, 5
CH = '.,=#Hr'                   # gulf, street, ring, chain-walk, house, rock (the mountain beyond the rim)

def main():
    d = json.load(open(SRC))
    R = max(max(abs(r[0]), abs(r[1]), abs(r[2]), abs(r[3])) for r in d['roads'])
    sx = W * SS / ((X1 - X0) * R); sy = H * SS / ((Y1 - Y0) * R)
    P = lambda x, y: ((x / R - X0) * R * sx, (y / R - Y0) * R * sy)
    cell_m = (X1 - X0) * R / W
    layers = {}
    for k in (STREET, RING, CHAIN, HOUSE):
        layers[k] = Image.new('L', (W * SS, H * SS), 0)
    dr = {k: ImageDraw.Draw(v) for k, v in layers.items()}
    for b in d['b']:
        x, y, bw, bd, rot = b[0], b[1], b[2], b[3], (b[6] if len(b) > 6 else 0)
        c, s = math.cos(rot), math.sin(rot)
        pts = [P(x + c * dx - s * dy, y + s * dx + c * dy) for dx, dy in ((-bw / 2, -bd / 2), (bw / 2, -bd / 2), (bw / 2, bd / 2), (-bw / 2, bd / 2))]
        dr[HOUSE].polygon(pts, fill=255)
    for r in d['roads']:
        k = CHAIN if r[5] == 'boulevard' else RING if r[5] in ('ring', 'wall') else STREET
        w = max(1, int(round(r[4] / cell_m * SS * (1.0 if k == CHAIN else 0.8))))
        dr[k].line([P(r[0], r[1]), P(r[2], r[3])], fill=255, width=w)
    small = {k: v.resize((W, H), Image.BOX) for k, v in layers.items()}
    grid = []
    for j in range(H):
        row = ''
        for i in range(W):
            nx = X0 + (i + 0.5) / W * (X1 - X0); ny = Y0 + (j + 0.5) / H * (Y1 - Y0)
            rr = math.hypot(nx, ny)
            v = lambda k: small[k].getpixel((i, j))
            if rr > 1.0: t = ROCK if ny < 0.9 else GULF
            elif v(CHAIN) > 70: t = CHAIN
            elif v(HOUSE) > 110: t = HOUSE
            elif v(RING) > 90 or v(STREET) > 90: t = RING if v(RING) >= v(STREET) else STREET
            else: t = GULF
            row += CH[t]
        grid.append(row)
    # run-length rows keep the file small and still readable
    def rle(s):
        out, i = [], 0
        while i < len(s):
            j = i
            while j < len(s) and s[j] == s[i]: j += 1
            n = j - i; out.append((str(n) if n > 1 else '') + s[i]); i = j
        return ''.join(out)
    js = ['// Generated by tools/maps/tiers92.py from the Cymatic City Engine\'s 528 Hz plan of Sol-Luminary (do not edit).',
          '// ' + str(W) + ' x ' + str(H) + ' cells, a cell a step and a half; rows run-length coded: ' + repr(CH) + ' = gulf, street, ring, chain-walk, house, rock.',
          "'use strict';",
          'const HEIGHTS92_GRID = { w: %d, h: %d, key: %s, rows: [' % (W, H, json.dumps(CH))]
    js += ['  %s,' % json.dumps(rle(r)) for r in grid]
    js += ['] };', "if (typeof window !== 'undefined') window.HEIGHTS92_GRID = HEIGHTS92_GRID;", "if (typeof module !== 'undefined' && module.exports) module.exports = HEIGHTS92_GRID;", '']
    open(os.path.join(ROOT, 'js', 'heights92_grid.js'), 'w').write('\n'.join(js))
    col = {'.': (24, 28, 40), ',': (150, 136, 112), '=': (190, 170, 130), '#': (210, 120, 60), 'H': (60, 52, 46), 'r': (90, 84, 80)}
    im = Image.new('RGB', (W, H))
    for j, r in enumerate(grid):
        for i, ch in enumerate(r): im.putpixel((i, j), col[ch])
    os.makedirs(os.path.join(ROOT, 'screenshots', 'p92'), exist_ok=True)
    im.resize((W * 4, H * 4), Image.NEAREST).save(os.path.join(ROOT, 'screenshots', 'p92', 'plan.png'))
    cnt = {k: sum(r.count(k) for r in grid) for k in CH}
    print('cell', round(cell_m, 1), 'm;', cnt)

main()
