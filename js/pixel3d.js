//  bearing and pose instead of the painted sprite (or the bestiary's hand-built view); a prop's sprite is swapped under
//  its own name. hs, cx and dy come from the bake (the model's real height in world units, where its feet stand), so a
//  creature keeps the size its def's scale gives it. Off, or until an atlas has loaded, the painted art draws exactly
//  as before. Nothing here touches saves, flags or the RNG.
// ============================================================
